"""Bundle registered, labelled synthetic PNGs. No downloads, credentials or database."""

import argparse
import base64
import json
from pathlib import Path

from medlm_api.synthetic_fixtures import FixtureRegistry, controlled_catalog, controlled_fixture

ROOT = Path(__file__).resolve().parents[1]


def fixtures():
    catalog = controlled_catalog() + tuple(
        controlled_fixture(kind, **variant)
        for kind in ("box", "prescription")
        for variant in ({"empty": True}, {"ambiguous": True})
    )
    FixtureRegistry(catalog)  # Validate actual original and sanitized bytes before generation.
    return catalog


def generate():
    items = [
        dict(**item.descriptor.model_dump(), image=base64.b64encode(item.original_bytes).decode())
        for item in fixtures()
    ]
    return "\n".join(
        [
            "// Generated by scripts/generate_synthetic_catalog.py. Do not edit.",
            "// Descriptive client catalog only; the server owns fixture admission/provenance.",
            "import 'dart:convert';",
            "import 'dart:typed_data';",
            "",
            "class BundledFixture {",
            "  BundledFixture._(this._data);",
            "  final Map<String, dynamic> _data;",
            "  String get id => _data['fixture_id'] as String;",
            "  int get revision => _data['fixture_revision'] as int;",
            "  String get kind => _data['document_kind'] as String;",
            "  String get mime => _data['mime'] as String;",
            "  String get originalHash => _data['original_sha256'] as String;",
            "  String get sanitizedHash => _data['sanitized_sha256'] as String;",
            "  Uint8List bytes() => base64Decode(_data['image'] as String);",
            "}",
            "final bundledFixtures = List<BundledFixture>.unmodifiable((jsonDecode(r'''",
            json.dumps(items, separators=(",", ":")),
            "''') as List).map((item) => BundledFixture._(Map<String, dynamic>.unmodifiable(item as Map<String, dynamic>))));",
            "",
        ]
    )


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    path = ROOT / "apps/medlm/lib/analysis/generated/synthetic_fixture_catalog.dart"
    content = generate()
    if args.check:
        if not path.exists() or path.read_text(encoding="utf-8") != content:
            raise SystemExit("Synthetic fixture catalog is stale")
    else:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8")
